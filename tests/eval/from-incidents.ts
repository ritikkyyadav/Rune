#!/usr/bin/env bun
/**
 * Incident → eval pipeline: turn the black box's recurring failure classes into
 * regression evals. This is the flywheel's input side — every fingerprint that
 * keeps firing is a reliability bug the scripted suite doesn't cover yet.
 *
 * Usage:
 *   bun run tests/eval/from-incidents.ts                 # report top recurring classes
 *   bun run tests/eval/from-incidents.ts --scaffold      # + write task stubs for uncovered ones
 *   bun run tests/eval/from-incidents.ts --db <path>     # non-default blackbox.db
 *   bun run tests/eval/from-incidents.ts --min-count 3 --since-days 30
 *
 * Workflow (documented in README.md):
 *   1. Run this after real usage. Classes firing ≥ min-count with no covering
 *      eval are listed as TODO.
 *   2. --scaffold writes tests/eval/from-incidents/<fp>.task.ts with the
 *      incident's shape baked in. Finish the stub: a deterministic setup +
 *      script reproducing the failure, and an artifact-checked verify.
 *   3. Promote the finished task into tasks-from-incidents.ts (imported by the
 *      suite) and record the fingerprint in from-incidents/covered.json.
 */
import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { join } from "node:path";

import { BlackboxStore } from "@gear/telemetry";

const SCAFFOLD_DIR = join(__dirname, "from-incidents");
const COVERED_PATH = join(SCAFFOLD_DIR, "covered.json");

interface CliArgs {
  db: string;
  minCount: number;
  sinceDays: number | undefined;
  scaffold: boolean;
}

function parseArgs(argv: string[]): CliArgs {
  const args: CliArgs = {
    db: join(homedir(), ".gear", "blackbox.db"),
    minCount: 3,
    sinceDays: 30,
    scaffold: false,
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--db") args.db = argv[++i];
    else if (a.startsWith("--db=")) args.db = a.slice("--db=".length);
    else if (a === "--min-count") args.minCount = Number(argv[++i]);
    else if (a.startsWith("--min-count=")) args.minCount = Number(a.slice("--min-count=".length));
    else if (a === "--since-days") args.sinceDays = Number(argv[++i]);
    else if (a.startsWith("--since-days="))
      args.sinceDays = Number(a.slice("--since-days=".length));
    else if (a === "--all-time") args.sinceDays = undefined;
    else if (a === "--scaffold") args.scaffold = true;
  }
  return args;
}

async function loadCovered(): Promise<Record<string, string>> {
  try {
    return JSON.parse(await readFile(COVERED_PATH, "utf8"));
  } catch {
    return {};
  }
}

/** A fingerprint is hex; the first 12 chars are unique enough for a filename. */
const short = (fp: string) => fp.slice(0, 12);

function scaffoldSource(fp: {
  fingerprint: string;
  class: string;
  component: string;
  messageSample: string;
  count: number;
  firstSeen: string;
  lastSeen: string;
}): string {
  // Bake the incident's identity into the stub so the finished eval stays
  // traceable back to the failure it reproduces.
  return `/**
 * Regression eval scaffold — generated by from-incidents.ts. FINISH ME.
 *
 * Incident class:   ${fp.class}
 * Component:        ${fp.component}
 * Fired:            ${fp.count}× (${fp.firstSeen} → ${fp.lastSeen})
 * Fingerprint:      ${fp.fingerprint}
 * Message sample:   ${fp.messageSample.replace(/\*\//g, "*\\/").slice(0, 200)}
 *
 * To finish:
 *  1. Write setup() building the smallest workspace that reproduces the shape.
 *  2. Script the tool sequence that used to trigger the failure.
 *  3. verify() must check ARTIFACTS (files, audit rows, exit codes) — never
 *     model prose.
 *  4. Export the task from tasks-from-incidents.ts and add
 *     "${fp.fingerprint}": "<task name>" to from-incidents/covered.json.
 */
import type { EvalTask } from "../harness";

export const TASK: EvalTask = {
  name: "incident_${short(fp.fingerprint)}",
  category: "core",
  description: ${JSON.stringify(`Reproduces incident class ${fp.class} (${fp.component})`)},
  setup: async ({ workspace: _workspace }) => {
    throw new Error("scaffold not finished — see header comment");
  },
  script: [],
  prompts: ["TODO"],
  verify: async () => ({ pass: false, reason: "scaffold not finished" }),
};
`;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));

  if (!existsSync(args.db)) {
    console.log(`\n  No black box at ${args.db} — nothing to mine yet.`);
    console.log(`  (Pass --db <path> to read a different incident store.)\n`);
    return;
  }

  const store = new BlackboxStore(args.db);
  const top = store.top({ limit: 100, sinceDays: args.sinceDays });
  const covered = await loadCovered();

  const recurring = top.filter((f) => f.count >= args.minCount);
  const uncovered = recurring.filter((f) => !covered[f.fingerprint]);

  const window = args.sinceDays !== undefined ? `last ${args.sinceDays} days` : "all time";
  console.log(
    `\n  \x1b[1mIncident → eval pipeline\x1b[0m \x1b[2m(${window}, min count ${args.minCount})\x1b[0m\n`,
  );

  if (recurring.length === 0) {
    console.log("  No incident class fired often enough to demand an eval. Good.\n");
    return;
  }

  const header = "  Count".padEnd(9) + "Class".padEnd(28) + "Component".padEnd(22) + "Covered by";
  console.log(`\x1b[2m${header}\x1b[0m`);
  console.log(`\x1b[2m${"─".repeat(90)}\x1b[0m`);
  for (const f of recurring) {
    const cov = covered[f.fingerprint];
    const covStr = cov ? `\x1b[32m${cov}\x1b[0m` : "\x1b[31mTODO\x1b[0m";
    console.log(
      `  ${String(f.count).padEnd(7)}${f.class.slice(0, 26).padEnd(28)}${f.component
        .slice(0, 20)
        .padEnd(22)}${covStr}`,
    );
    console.log(`  \x1b[2m       ${f.messageSample.slice(0, 76)}\x1b[0m`);
  }
  console.log();

  if (!args.scaffold) {
    if (uncovered.length > 0) {
      console.log(
        `  ${uncovered.length} class(es) uncovered — run with \x1b[1m--scaffold\x1b[0m to generate task stubs.\n`,
      );
    }
    return;
  }

  await mkdir(SCAFFOLD_DIR, { recursive: true });
  let written = 0;
  for (const f of uncovered) {
    const path = join(SCAFFOLD_DIR, `${short(f.fingerprint)}.task.ts`);
    if (existsSync(path)) continue; // never clobber an in-progress stub
    await writeFile(path, scaffoldSource(f));
    console.log(`  scaffolded ${path}`);
    written++;
  }
  if (!existsSync(COVERED_PATH)) {
    await writeFile(COVERED_PATH, "{}\n");
  }
  console.log(
    written > 0
      ? `\n  ${written} stub(s) written. Finish them, promote into tasks-from-incidents.ts, and record the fingerprints in covered.json.\n`
      : "\n  Nothing new to scaffold (all uncovered classes already have stubs in progress).\n",
  );
}

main().catch((err) => {
  console.error("Fatal:", err);
  process.exit(2);
});
